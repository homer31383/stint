function balanceFor(d: DetailedBalances, key: FixedAccountKey): number {
  if (HOLDINGS_ENABLED_KEYS.includes(key as HoldingsAccountKey)) {
    return effectiveBalance(d, key as HoldingsAccountKey);
  }
  return d[key] as number;
}

export function buildBriefing(input: BriefingInput): string {
  const today = new Date();
  const todayStr = today.toISOString().slice(0, 10);

  const sections: string[] = [];
  sections.push(`# Financial Briefing — ${todayStr}\n\n*Generated by Stint Ledger for analysis by Claude.*`);
  sections.push(buildProfile(input));
  sections.push(buildFinancialPosition(input));
  sections.push(buildHoldings(input));
  sections.push(buildIncomeWork(input));
  sections.push(buildInvoiceStatus(input));
  sections.push(buildExpenses(input));
  sections.push(buildCashFlow(input));
  sections.push(buildProjections(input));
  sections.push(buildRetirement(input));
  sections.push(buildSavedScenarios(input));
  sections.push(buildQuestions(input));

  return sections.join('\n\n---\n\n') + '\n';
}

